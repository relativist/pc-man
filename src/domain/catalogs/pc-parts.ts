function buildScore(level: number): number {
  return 9 + (level - 1) * 9;
}

function buildPrice(level: number): number {
  return Math.round(260 + level * 125 + level * level * 18);
}

export const pcTierCatalog: PcTierCatalogItem[] = pcTierTitles.map((title, index) => {
  const level = index + 1;

  return {
    id: `pc-tier-${level}`,
    level,
    title,
    funnyTitle: `${title} workstation tier ${level}`,
    score: buildScore(level),
    price: buildPrice(level),
    specs: {
      cpu: cpuModels[index],
      gpu: gpuModels[index],
      ram: ramModels[index],
      storage: storageModels[index],
      motherboard: motherboardModels[index],
      psu: psuModels[index],
      cooling: coolingModels[index],
      case: caseModels[index],
      monitor: monitorModels[index],
      peripherals: peripheralModels[index],
    },
  };
});
